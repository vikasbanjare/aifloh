import { chromium } from 'playwright-core';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 1440, height: 900 } });
const errs=[]; p.on('console',m=>m.type()==='error'&&errs.push(m.text())); p.on('pageerror',e=>errs.push(String(e)));
await p.goto('http://localhost:4331/');
console.log('h264', await p.evaluate(()=>document.createElement('video').canPlayType('video/mp4; codecs="avc1.640028"')), 'vp9', await p.evaluate(()=>document.createElement('video').canPlayType('video/webm; codecs="vp9"')));
await p.evaluate(() => document.documentElement.classList.remove('booting'));
await p.mouse.move(5,5); await p.waitForTimeout(3000);
console.log(await p.evaluate(()=>{const v=document.querySelector('.film-video');return [document.querySelector('.film-stage').className, v&&v.readyState, v&&v.duration, v&&v.error&&v.error.code].join(' | ')}));
console.log(errs.join('\n')||'no errors');
await b.close();
